

CREATE TABLE IF NOT EXISTS users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, school_id VARCHAR(30) UNIQUE NOT NULL, full_name VARCHAR(120) NOT NULL,
 email VARCHAR(120) UNIQUE, password_hash VARCHAR(255) NULL, role VARCHAR(30) NOT NULL DEFAULT 'student' CHECK (role IN ('admin','staff','student','faculty')),
 department VARCHAR(100), active SMALLINT DEFAULT 1 CHECK (active IN (0,1)), activation_required SMALLINT NOT NULL DEFAULT 0 CHECK (activation_required IN (0,1)), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);



CREATE TABLE IF NOT EXISTS auth_sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_scope VARCHAR(64) UNIQUE NOT NULL,
 token_hash CHAR(64) UNIQUE NOT NULL,
 user_id INT NOT NULL,
 role VARCHAR(30) NOT NULL DEFAULT 'student' CHECK (role IN ('student','faculty')),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 last_seen TIMESTAMP NULL,
 expires_at TIMESTAMP NOT NULL,
 revoked SMALLINT DEFAULT 0 CHECK (revoked IN (0,1)),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS student_records (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id VARCHAR(30) UNIQUE NOT NULL,
 full_name VARCHAR(120) NOT NULL,
 email VARCHAR(120),
 program VARCHAR(120),
 year_level VARCHAR(30),
 section VARCHAR(60),
 user_id INT UNIQUE NULL,
 active SMALLINT DEFAULT 1 CHECK (active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 registered_at TIMESTAMP NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS categories (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(80) UNIQUE NOT NULL, description VARCHAR(255));
CREATE TABLE IF NOT EXISTS equipment (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, asset_code VARCHAR(40) UNIQUE NOT NULL, serial_number VARCHAR(100) UNIQUE NOT NULL, name VARCHAR(120) NOT NULL, model VARCHAR(120) NOT NULL, category_id INT,
 description TEXT, total_qty INT NOT NULL DEFAULT 1, available_qty INT NOT NULL DEFAULT 1,
 condition_status VARCHAR(30) DEFAULT 'Good' CHECK (condition_status IN ('Good','Fair','For Repair','Damaged')), location VARCHAR(120), image_filename VARCHAR(255) NULL,
 archived SMALLINT NOT NULL DEFAULT 0 CHECK (archived IN (0,1)), fair_cost DECIMAL(10,2) NOT NULL DEFAULT 250.00, damage_cost DECIMAL(10,2) NOT NULL DEFAULT 1000.00, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(category_id) REFERENCES categories(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS borrow_requests (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, borrower_id INT NOT NULL, equipment_id INT NOT NULL, quantity INT NOT NULL DEFAULT 1,
 purpose VARCHAR(255) NOT NULL, borrow_date DATE NOT NULL, due_date DATE NOT NULL,
 status VARCHAR(30) DEFAULT 'Pending' CHECK (status IN ('Pending','Approved','Rejected','Released','Returned','Overdue','Cancelled')),
 reviewed_by INT NULL, reviewed_at TIMESTAMP NULL, released_at TIMESTAMP NULL, returned_at TIMESTAMP NULL, return_requested_at TIMESTAMP NULL, return_condition VARCHAR(50), remarks TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(borrower_id) REFERENCES users(id), FOREIGN KEY(equipment_id) REFERENCES equipment(id), FOREIGN KEY(reviewed_by) REFERENCES users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS notifications (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INT NOT NULL, message TEXT NOT NULL, is_read SMALLINT DEFAULT 0 CHECK (is_read IN (0,1)), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS equipment_units (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, equipment_id INT NOT NULL,
            serial_number VARCHAR(100) NOT NULL UNIQUE,
            condition_status VARCHAR(20) NOT NULL DEFAULT 'Good',
            active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
            current_request_id INT NULL, needs_serial SMALLINT NOT NULL DEFAULT 0 CHECK (needs_serial IN (0,1)),
            FOREIGN KEY(equipment_id) REFERENCES equipment(id),
            FOREIGN KEY(current_request_id) REFERENCES borrow_requests(id)
);

CREATE TABLE IF NOT EXISTS borrow_request_units (
            request_id INT NOT NULL, unit_id INT NOT NULL,
            serial_at_release VARCHAR(100) NOT NULL,
            PRIMARY KEY(request_id,unit_id),
            FOREIGN KEY(request_id) REFERENCES borrow_requests(id),
            FOREIGN KEY(unit_id) REFERENCES equipment_units(id));

CREATE TABLE IF NOT EXISTS equipment_damage (
        request_id INT PRIMARY KEY, description TEXT NOT NULL,
        reported_by INT NOT NULL, reported_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        responsibility_ack_at TIMESTAMP NULL,
        amount DECIMAL(10,2) NULL, assessment_notes TEXT NULL,
        assessed_by INT NULL, assessed_at TIMESTAMP NULL, assessment_version INT NOT NULL DEFAULT 0,
        cost_ack_at TIMESTAMP NULL, paid_at TIMESTAMP NULL, paid_by INT NULL,
        payment_reference VARCHAR(120) NULL, borrower_explanation TEXT NULL, explanation_at TIMESTAMP NULL,
        FOREIGN KEY(request_id) REFERENCES borrow_requests(id),
        FOREIGN KEY(reported_by) REFERENCES users(id),
        FOREIGN KEY(assessed_by) REFERENCES users(id),
        FOREIGN KEY(paid_by) REFERENCES users(id)
    );

CREATE TABLE IF NOT EXISTS borrower_terms_acceptance (
            user_id INT NOT NULL, terms_version VARCHAR(40) NOT NULL,
            accepted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY(user_id,terms_version),
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
        );

CREATE TABLE IF NOT EXISTS transaction_view_state (
            user_id INT PRIMARY KEY,
            cleared_through_request_id INT NOT NULL DEFAULT 0,
            cleared_at TIMESTAMP NULL,
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
        );

CREATE INDEX IF NOT EXISTS idx_auth_user ON auth_sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_auth_expiry ON auth_sessions(expires_at);
CREATE INDEX IF NOT EXISTS equipment_units_inventory ON equipment_units(equipment_id,active);
CREATE INDEX IF NOT EXISTS notifications_user_read ON notifications(user_id,is_read);
CREATE INDEX IF NOT EXISTS borrowing_user_status ON borrow_requests(borrower_id,status);
